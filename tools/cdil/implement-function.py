#!/usr/bin/env python3
"""
One-button function implementation tool
Assembles Spec slice + stubs + validators, prompts LLM, 
applies patch with AST guard
"""
import argparse
import os
import subprocess
import sys
from typing import Dict, Optional


def assemble_spec_context(spec_id: str) -> Dict[str, Optional[str]]:
    """
    Assemble the specification context for a function.
    """
    context: Dict[str, Optional[str]] = {
        "spec": None,
        "stubs": None,
        "validators": None
    }
    
    # Load spec
    spec_file = f"specs/{spec_id}.yaml"
    if os.path.exists(spec_file):
        with open(spec_file, 'r') as f:
            context["spec"] = f.read()
    
    # Load stubs
    stub_file = f"contracts/{spec_id.replace('.', '/')}.pyi"
    if os.path.exists(stub_file):
        with open(stub_file, 'r') as f:
            context["stubs"] = f.read()
    
    # Load validators
    validator_file = f"contracts/{spec_id.replace('.', '/')}/validators.py"
    if os.path.exists(validator_file):
        with open(validator_file, 'r') as f:
            context["validators"] = f.read()
    
    return context


